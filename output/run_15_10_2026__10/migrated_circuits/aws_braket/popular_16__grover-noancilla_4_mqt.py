# Importación de paquetes requeridos
import math
from braket.circuits import Circuit

# Creación del circuito AWS Braket
circuit = Circuit()

# Puertas migradas desde OpenQASM
circuit.h(0)
circuit.h(1)
circuit.h(2)
circuit.x(3)
circuit.cphaseshift([2], 3, math.pi/4)
circuit.x(1, control=[2])
circuit.cphaseshift([1], 3, -math.pi/4)
circuit.x(1, control=[2])
circuit.cphaseshift([1], 3, math.pi/4)
circuit.x(0, control=[1])
circuit.cphaseshift([0], 3, -math.pi/4)
circuit.x(0, control=[2])
circuit.cphaseshift([0], 3, math.pi/4)
circuit.x(0, control=[1])
circuit.cphaseshift([0], 3, -math.pi/4)
circuit.ry(1, math.pi/2)
circuit.x(0, control=[2])
circuit.cphaseshift([0], 3, math.pi/4)
circuit.ry(0, math.pi/2)
circuit.z(2)
circuit.x(2, control=[0, 1])
circuit.ry(0, -math.pi/2)
circuit.ry(1, -math.pi/2)
circuit.z(2)
circuit.cphaseshift([2], 3, math.pi/4)
circuit.x(1, control=[2])
circuit.cphaseshift([1], 3, -math.pi/4)
circuit.x(1, control=[2])
circuit.cphaseshift([1], 3, math.pi/4)
circuit.x(0, control=[1])
circuit.cphaseshift([0], 3, -math.pi/4)
circuit.x(0, control=[2])
circuit.cphaseshift([0], 3, math.pi/4)
circuit.x(0, control=[1])
circuit.cphaseshift([0], 3, -math.pi/4)
circuit.ry(1, math.pi/2)
circuit.x(0, control=[2])
circuit.cphaseshift([0], 3, math.pi/4)
circuit.ry(0, math.pi/2)
circuit.z(2)
circuit.x(2, control=[0, 1])
circuit.ry(0, -math.pi/2)
circuit.ry(1, -math.pi/2)
circuit.z(2)

# Mediciones en orden clásico, diferidas al final
circuit.measure([0])
circuit.measure([1])
circuit.measure([2])
circuit.measure([3])
