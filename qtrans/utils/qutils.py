"""Fachada de compatibilidad de ``qtrans.utils.qutils``.

Antes de la reorganización, ``qutils`` concentraba la traducción desde Quirk,
las utilidades de OpenQASM y el registro de proveedores. Esa lógica vive ahora
en módulos con responsabilidad única:

- ``qasm_utils``: tablas de ``stdgates.inc``, nombres, ángulos, versiones y resumen.
- ``quirk_utils``: traducción Quirk → OpenQASM, captura de imágenes y comparación.
- ``provider_utils``: registro de proveedores, dispatch y carga de circuitos.
- ``qiskit_utils`` / ``braket_utils`` / ``pennylane_utils``: lógica de cada ecosistema.
- ``zx_utils``: grafos ZX (PyZX).
- ``url_utils``: URLs de Quirk.

Este módulo se conserva como punto de entrada estable: reexporta los nombres
públicos y privados más usados para no romper los imports existentes (cuadernos
y suite de tests) y para mantener compatibilidad hacia atrás.
"""

