# Importación de paquetes requeridos
from qiskit import QuantumCircuit, QuantumRegister, ClassicalRegister
from qiskit.circuit.library import HGate, SwapGate

# Generación de registros cuánticos y clásicos
qreg_q = QuantumRegister(6, 'q')
creg_c = ClassicalRegister(6, 'c')

# Creación del circuito cuántico
circuit = QuantumCircuit(qreg_q, creg_c)

circuit.h(qreg_q[0])
circuit.h(qreg_q[1])
circuit.h(qreg_q[2])
circuit.h(qreg_q[3])
circuit.h(qreg_q[4])
circuit.h(qreg_q[5])
circuit.x(qreg_q[0])
circuit.cx(qreg_q[0], qreg_q[1])
circuit.cx(qreg_q[0], qreg_q[1])
circuit.cx(qreg_q[0], qreg_q[2])
circuit.cx(qreg_q[0], qreg_q[1])
circuit.cx(qreg_q[0], qreg_q[2])
circuit.cx(qreg_q[0], qreg_q[3])
circuit.mcx([qreg_q[0], qreg_q[1], qreg_q[2], qreg_q[3]], qreg_q[4])
circuit.h(qreg_q[0])
circuit.ch(qreg_q[0], qreg_q[1])
circuit.ch(qreg_q[0], qreg_q[1])
circuit.ch(qreg_q[0], qreg_q[2])
circuit.ch(qreg_q[0], qreg_q[1])
circuit.ch(qreg_q[0], qreg_q[2])
circuit.ch(qreg_q[0], qreg_q[3])
circuit.append(HGate().control(4), [qreg_q[0], qreg_q[1], qreg_q[2], qreg_q[3], qreg_q[4]])
circuit.y(qreg_q[0])
circuit.cy(qreg_q[0], qreg_q[1])
circuit.cy(qreg_q[0], qreg_q[1])
circuit.cy(qreg_q[0], qreg_q[2])
circuit.cy(qreg_q[0], qreg_q[1])
circuit.cy(qreg_q[0], qreg_q[2])
circuit.cy(qreg_q[0], qreg_q[3])
circuit.cy(qreg_q[0], qreg_q[4])
circuit.z(qreg_q[0])
circuit.cz(qreg_q[0], qreg_q[1])
circuit.cz(qreg_q[0], qreg_q[1])
circuit.cz(qreg_q[0], qreg_q[2])
circuit.cz(qreg_q[0], qreg_q[1])
circuit.cz(qreg_q[0], qreg_q[2])
circuit.cz(qreg_q[0], qreg_q[3])
circuit.cz(qreg_q[0], qreg_q[4])
circuit.swap(qreg_q[0], qreg_q[1])
circuit.cswap(qreg_q[0], qreg_q[1], qreg_q[2])
circuit.append(SwapGate().control(2), [qreg_q[0], qreg_q[1], qreg_q[2], qreg_q[3]])
circuit.append(SwapGate().control(4), [qreg_q[0], qreg_q[1], qreg_q[3], qreg_q[4], qreg_q[2], qreg_q[5]])
