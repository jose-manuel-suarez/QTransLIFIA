# Importación de paquetes requeridos
import math
from qiskit import QuantumCircuit, QuantumRegister, ClassicalRegister

# Generación de registros cuánticos y clásicos
qreg_q = QuantumRegister(6, 'q')
creg_c = ClassicalRegister(6, 'c')

# Compuertas personalizadas (funciones locales)
def QFT6(circuit, w0, w1, w2, w3, w4, w5):
    circuit.h(w5)
    circuit.cp(math.pi/2, w5, w4)
    circuit.cp(math.pi/4, w5, w3)
    circuit.cp(math.pi/8, w5, w2)
    circuit.cp(math.pi/16, w5, w1)
    circuit.cp(math.pi/32, w5, w0)
    circuit.h(w4)
    circuit.cp(math.pi/2, w4, w3)
    circuit.cp(math.pi/4, w4, w2)
    circuit.cp(math.pi/8, w4, w1)
    circuit.cp(math.pi/16, w4, w0)
    circuit.h(w3)
    circuit.cp(math.pi/2, w3, w2)
    circuit.cp(math.pi/4, w3, w1)
    circuit.cp(math.pi/8, w3, w0)
    circuit.h(w2)
    circuit.cp(math.pi/2, w2, w1)
    circuit.cp(math.pi/4, w2, w0)
    circuit.h(w1)
    circuit.cp(math.pi/2, w1, w0)
    circuit.h(w0)
    circuit.swap(w0, w5)
    circuit.swap(w1, w4)
    circuit.swap(w2, w3)

def QFT6_dg(circuit, w0, w1, w2, w3, w4, w5):
    circuit.swap(w0, w5)
    circuit.swap(w1, w4)
    circuit.swap(w2, w3)
    circuit.h(w0)
    circuit.cp(-math.pi/2, w1, w0)
    circuit.h(w1)
    circuit.cp(-math.pi/4, w2, w0)
    circuit.cp(-math.pi/2, w2, w1)
    circuit.h(w2)
    circuit.cp(-math.pi/8, w3, w0)
    circuit.cp(-math.pi/4, w3, w1)
    circuit.cp(-math.pi/2, w3, w2)
    circuit.h(w3)
    circuit.cp(-math.pi/16, w4, w0)
    circuit.cp(-math.pi/8, w4, w1)
    circuit.cp(-math.pi/4, w4, w2)
    circuit.cp(-math.pi/2, w4, w3)
    circuit.h(w4)
    circuit.cp(-math.pi/32, w5, w0)
    circuit.cp(-math.pi/16, w5, w1)
    circuit.cp(-math.pi/8, w5, w2)
    circuit.cp(-math.pi/4, w5, w3)
    circuit.cp(-math.pi/2, w5, w4)
    circuit.h(w5)

# Creación del circuito cuántico
circuit = QuantumCircuit(qreg_q, creg_c)

circuit.h(qreg_q[0])
circuit.h(qreg_q[1])
circuit.h(qreg_q[2])
circuit.h(qreg_q[3])
circuit.h(qreg_q[4])
circuit.h(qreg_q[5])
QFT6(circuit, qreg_q[0], qreg_q[1], qreg_q[2], qreg_q[3], qreg_q[4], qreg_q[5])
QFT6_dg(circuit, qreg_q[0], qreg_q[1], qreg_q[2], qreg_q[3], qreg_q[4], qreg_q[5])
circuit.measure(qreg_q[0], creg_c[0])
circuit.measure(qreg_q[1], creg_c[1])
circuit.measure(qreg_q[2], creg_c[2])
circuit.measure(qreg_q[3], creg_c[3])
circuit.measure(qreg_q[4], creg_c[4])
circuit.measure(qreg_q[5], creg_c[5])
