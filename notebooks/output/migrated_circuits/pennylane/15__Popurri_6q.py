# Importación de paquetes requeridos
import pennylane as qml

device = qml.device('default.qubit', wires=6, shots=None)

@qml.qnode(device)
def circuit():
    qml.Hadamard(wires=0)
    qml.Hadamard(wires=1)
    qml.Hadamard(wires=2)
    qml.Hadamard(wires=3)
    qml.Hadamard(wires=4)
    qml.Hadamard(wires=5)
    qml.PauliX(wires=0)
    qml.ctrl(qml.PauliX, control=[0])(wires=1)
    qml.ctrl(qml.PauliX, control=[0])(wires=1)
    qml.ctrl(qml.PauliX, control=[0])(wires=2)
    qml.ctrl(qml.PauliX, control=[0])(wires=1)
    qml.ctrl(qml.PauliX, control=[0])(wires=2)
    qml.ctrl(qml.PauliX, control=[0])(wires=3)
    qml.ctrl(qml.PauliX, control=[0, 1, 2, 3])(wires=4)
    qml.Hadamard(wires=0)
    qml.ctrl(qml.Hadamard, control=[0])(wires=1)
    qml.ctrl(qml.Hadamard, control=[0])(wires=1)
    qml.ctrl(qml.Hadamard, control=[0])(wires=2)
    qml.ctrl(qml.Hadamard, control=[0])(wires=1)
    qml.ctrl(qml.Hadamard, control=[0])(wires=2)
    qml.ctrl(qml.Hadamard, control=[0])(wires=3)
    qml.ctrl(qml.Hadamard, control=[0, 1, 2, 3])(wires=4)
    qml.PauliY(wires=0)
    qml.ctrl(qml.PauliY, control=[0])(wires=1)
    qml.ctrl(qml.PauliY, control=[0])(wires=1)
    qml.ctrl(qml.PauliY, control=[0])(wires=2)
    qml.ctrl(qml.PauliY, control=[0])(wires=1)
    qml.ctrl(qml.PauliY, control=[0])(wires=2)
    qml.ctrl(qml.PauliY, control=[0])(wires=3)
    qml.ctrl(qml.PauliY, control=[0])(wires=4)
    qml.PauliZ(wires=0)
    qml.ctrl(qml.PauliZ, control=[0])(wires=1)
    qml.ctrl(qml.PauliZ, control=[0])(wires=1)
    qml.ctrl(qml.PauliZ, control=[0])(wires=2)
    qml.ctrl(qml.PauliZ, control=[0])(wires=1)
    qml.ctrl(qml.PauliZ, control=[0])(wires=2)
    qml.ctrl(qml.PauliZ, control=[0])(wires=3)
    qml.ctrl(qml.PauliZ, control=[0])(wires=4)
    qml.SWAP(wires=[0, 1])
    qml.ctrl(qml.SWAP, control=[0])(wires=[1, 2])
    qml.ctrl(qml.SWAP, control=[0, 1])(wires=[2, 3])
    qml.ctrl(qml.SWAP, control=[0, 1, 3, 4])(wires=[2, 5])
    return qml.state()
